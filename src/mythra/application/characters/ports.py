"""Interface de persistência consumida pelos casos de uso de personagens."""

from typing import Any, Protocol
from uuid import UUID


class CharacterStore(Protocol):
    def create(self, *, story_id: UUID, values: dict[str, Any]) -> Any: ...
    def list_for_story(self, story_id: UUID) -> list[Any]: ...
    def get_in_story(self, story_id: UUID, character_id: UUID) -> Any | None: ...
    def update_character(self, character: Any, changes: dict[str, Any]) -> Any: ...
    def create_fact(self, *, story_id: UUID, values: dict[str, Any]) -> Any: ...
    def list_facts(self, story_id: UUID) -> list[Any]: ...
    def get_fact_in_story(self, story_id: UUID, fact_id: UUID) -> Any | None: ...
    def update_fact(self, fact: Any, changes: dict[str, Any]) -> Any: ...
    def create_knowledge(self, *, character_id: UUID, values: dict[str, Any]) -> Any: ...
    def list_knowledge(self, character_id: UUID) -> list[Any]: ...
    def list_knowledge_for_story(self, story_id: UUID) -> list[Any]: ...
    def get_knowledge_in_story(
        self, story_id: UUID, character_id: UUID, fact_id: UUID
    ) -> Any | None: ...
    def get_knowledge_by_id_in_story(self, story_id: UUID, knowledge_id: UUID) -> Any | None: ...
    def update_knowledge(self, knowledge: Any, changes: dict[str, Any]) -> Any: ...
    def create_relationship(self, *, story_id: UUID, values: dict[str, Any]) -> Any: ...
    def list_relationships(self, story_id: UUID) -> list[Any]: ...
    def get_relationship_in_story(self, story_id: UUID, relationship_id: UUID) -> Any | None: ...
    def update_relationship(self, relationship: Any, changes: dict[str, Any]) -> Any: ...
