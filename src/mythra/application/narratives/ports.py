"""Interface de persistência consumida pelos casos de uso narrativos."""

from typing import Any, Protocol
from uuid import UUID


class NarrativeStore(Protocol):
    def create_timeline_event(self, *, story_id: UUID, values: dict[str, Any]) -> Any: ...
    def list_timeline_events(self, story_id: UUID) -> list[Any]: ...
    def get_timeline_event_in_story(
        self, story_id: UUID, timeline_event_id: UUID
    ) -> Any | None: ...
    def update_timeline_event(self, record: Any, changes: dict[str, Any]) -> Any: ...
    def create_plot_thread(self, *, story_id: UUID, values: dict[str, Any]) -> Any: ...
    def list_plot_threads(self, story_id: UUID) -> list[Any]: ...
    def get_plot_thread_in_story(self, story_id: UUID, plot_thread_id: UUID) -> Any | None: ...
    def update_plot_thread(self, record: Any, changes: dict[str, Any]) -> Any: ...
    def create_arc(self, *, story_id: UUID, values: dict[str, Any]) -> Any: ...
    def get_arc(self, arc_id: UUID) -> Any | None: ...
    def list_arcs(self, story_id: UUID) -> list[Any]: ...
    def get_arc_in_story(self, story_id: UUID, arc_id: UUID) -> Any | None: ...
    def update_arc(self, record: Any, changes: dict[str, Any]) -> Any: ...
    def create_chapter(self, *, story_id: UUID, values: dict[str, Any]) -> Any: ...
    def list_chapters(self, story_id: UUID) -> list[Any]: ...
    def get_chapter_in_story(self, story_id: UUID, chapter_id: UUID) -> Any | None: ...
    def update_chapter(self, record: Any, changes: dict[str, Any]) -> Any: ...
